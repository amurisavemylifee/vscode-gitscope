/**
 * Перенос длинных строк.
 *
 * Строки виртуализованы, а виртуализатору нужна высота до отрисовки — значит
 * число визуальных строк надо считать, а не мерить у готовой вёрстки. Считать
 * его можно только потому, что перенос жёсткий (`word-break: break-all`): строка
 * рвётся ровно там, где кончилась ширина, и число кусков равно
 * `ceil(ширина текста / колонок)`. Перенос по границам слов дал бы кусков
 * больше, и предсказать сколько — уже нельзя.
 *
 * Ширину ячейки кода канва задаёт тем же числом колонок (`--gs-wrap-columns`),
 * поэтому вёрстка и расчёт не могут разойтись: обе стороны считают по одному
 * числу, а не по одинаково угаданным пикселям.
 */

/** Шаг табуляции — `tab-size` в CSS строк кода. */
const TAB_SIZE = 4;

/**
 * Ширина жёлоба слева от кода: сумма колонок сетки строки.
 * Держать их в согласии с CSS обязательно, но не критично: ошибка здесь
 * отнимет от ширины кода пару символов, а не разъедет вёрстку с расчётом.
 */
export const GUTTER_UNIFIED = 110; // 46 + 46 + 18
export const GUTTER_SPLIT = 64; // 46 + 18 на половину
export const GUTTER_CONTENT = 56; // один номер строки в просмотре файла
/** Правый отступ ячейки кода — var(--gs-space-4). */
export const CODE_PADDING = 16;
/**
 * Запас ширины ячейки на случай, если ch и настоящая ширина символа разойдутся
 * в дробной части. Тот же пиксель прибавлен к --gs-code-cell в CSS: не вычти
 * его здесь — и на ширинах, где колонки ложатся ровно, строка вылезала бы за
 * панель, а под ней появлялась бы горизонтальная прокрутка на один пиксель.
 */
export const CELL_EPSILON = 1;

/**
 * Ширина текста в колонках.
 *
 * Табуляция дотягивает до следующей отметки. Иероглифы и знаки полной ширины
 * занимают две колонки — без этого строка из них считалась бы вдвое короче, и
 * её хвост наезжал бы на следующую строку.
 */
export function displayWidth(text: string): number {
  let width = 0;

  // Хвостовые пробелы при переносе повисают за краем и своей строки не занимают.
  for (const char of text.replace(/[ \t]+$/, '')) {
    if (char === '\t') {
      width = (Math.floor(width / TAB_SIZE) + 1) * TAB_SIZE;
    } else {
      width += WIDE.test(char) ? 2 : 1;
    }
  }

  return width;
}

/** Сколько визуальных строк занимает текст. Пустая строка — всё равно одна. */
export function visualLines(text: string, columns: number): number {
  if (columns <= 0) {
    return 1;
  }
  return Math.max(1, Math.ceil(displayWidth(text) / columns));
}

/**
 * Знаки, занимающие в моноширинном шрифте две колонки: иероглифы, кана, хангыль
 * и знаки полной ширины (East Asian Wide и Fullwidth).
 */
const WIDE =
  /[\u1100-\u115f\u2e80-\u303e\u3041-\u33ff\u3400-\u4dbf\u4e00-\u9fff\ua000-\ua4cf\uac00-\ud7a3\uf900-\ufaff\ufe30-\ufe6f\uff00-\uff60\uffe0-\uffe6]/;
